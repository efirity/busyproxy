import Foundation

/// In-app languages (match Android BusyProxy set).
enum AppLanguage: String, CaseIterable, Identifiable {
    case en
    case es
    case zhHans = "zh-Hans"
    case hi
    case ptBR = "pt-BR"

    var id: String { rawValue }

    /// Native label shown in the language menu (not localized).
    var menuTitle: String {
        switch self {
        case .en: return "English"
        case .es: return "Español"
        case .zhHans: return "简体中文"
        case .hi: return "हिन्दी"
        case .ptBR: return "Português"
        }
    }

    var localeIdentifier: String { rawValue }
}

/// Compact string table — no .strings file plumbing required for sim builds.
enum L10n {
    private static let defaultsKey = "bp.language"

    static var language: AppLanguage {
        get {
            let raw = UserDefaults.standard.string(forKey: defaultsKey) ?? "en"
            return AppLanguage(rawValue: raw) ?? .en
        }
        set {
            UserDefaults.standard.set(newValue.rawValue, forKey: defaultsKey)
        }
    }

    static func t(_ key: String) -> String {
        let lang = language
        if let v = table[lang]?[key] { return v }
        if let v = table[.en]?[key] { return v }
        return key
    }

    static func t(_ key: String, _ args: CVarArg...) -> String {
        String(format: t(key), locale: Locale(identifier: language.localeIdentifier), arguments: args)
    }

